def pairs(axis: str, tasks: list[str] | None = None) -> list[tuple[str, str, int]]:
    """(pos_prompt, neg_prompt, phrasing_index) pairs. Default task set = 40 extraction chat tasks + 12 ops tasks
    = 260 pairs; pass a task list to extract on a subset (e.g. chat-only vs ops-only for the register check)."""
    ax = AXES[axis]
    tasks = (EXTRACT_TASKS + OPS_TASKS) if tasks is None else tasks
    return [(f"{t}\n\n{p}", f"{t}\n\n{n}", i) for t in tasks for i, (p, n) in enumerate(zip(ax["pos"], ax["neg"]))]


